export function getStudentById(id: string): Student | undefined {
  return students.find((s) => s.id.toLowerCase() === id.toLowerCase());
}

export function getStudentsBySpecialization(specSlug: string): Student[] {
  return students.filter((s) => s.specializationSlug.toLowerCase() === specSlug.toLowerCase());
}

export function getStudentsByDepartment(deptSlug: string): Student[] {
  return students.filter((s) => s.departmentSlug.toLowerCase() === deptSlug.toLowerCase());
}
